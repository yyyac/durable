import { test, expect } from './fixtures';

test('创建和切换独立会话，刷新后保留列表、选择和各自历史', async ({ page, workbench, upstream }) => {
  await page.goto(workbench.url);
  await page.getByRole('button', { name: '打开设置' }).click();
  await page.getByLabel('接口地址').fill(upstream.url);
  await page.getByLabel('API Key', { exact: true }).fill('conversation-test-secret');
  await page.getByLabel('模型 ID').fill('test-model');
  await page.getByLabel('模型名称').fill('会话测试模型');
  await page.getByRole('button', { name: '保存配置' }).click();
  upstream.enqueue({ chunks: ['甲会话的独立回复'] });
  await page.getByRole('textbox', { name: '输入消息' }).fill('甲会话问题');
  await page.getByRole('button', { name: '发送消息' }).click();
  await expect(page.getByTestId('assistant-message')).toHaveText('甲会话的独立回复');
  const firstUrl = page.url();
  await page.getByRole('button', { name: '新建会话', exact: true }).click();
  await expect(page.getByTestId('assistant-message')).toHaveCount(0);
  upstream.enqueue({ chunks: ['乙会话的独立回复'] });
  await page.getByRole('textbox', { name: '输入消息' }).fill('乙会话问题');
  await page.getByRole('button', { name: '发送消息' }).click();
  await expect(page.getByTestId('assistant-message')).toHaveText('乙会话的独立回复');
  const secondUrl = page.url();
  expect(secondUrl).not.toBe(firstUrl);
  await page.getByRole('button', { name: '甲会话问题', exact: true }).click();
  await expect(page).toHaveURL(firstUrl);
  await expect(page.getByTestId('assistant-message')).toHaveText('甲会话的独立回复');
  await expect(page.getByTestId('user-message')).toHaveText('甲会话问题');
  await page.reload();
  await expect(page.getByRole('button', { name: '甲会话问题', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(page.getByRole('button', { name: '乙会话问题', exact: true })).toBeVisible();
  await expect(page.getByTestId('assistant-message')).toHaveText('甲会话的独立回复');
  await page.getByRole('button', { name: '乙会话问题', exact: true }).click();
  await expect(page).toHaveURL(secondUrl);
  await expect(page.getByTestId('user-message')).toHaveText('乙会话问题');
  await expect(page.getByTestId('assistant-message')).toHaveText('乙会话的独立回复');
  expect(upstream.requests).toHaveLength(2);
  expect(upstream.requests[1].messages.filter((message) => message.role === 'user')).toEqual([{ role: 'user', content: '乙会话问题' }]);
  await page.goBack();
  await expect(page).toHaveURL(firstUrl);
  await expect(page.getByTestId('assistant-message')).toHaveText('甲会话的独立回复');
});

test('不同会话并行生成，离开和返回只切换观察，旧会话更新不会覆盖当前会话', async ({ page, workbench, upstream }) => {
  await page.goto(workbench.url);
  await page.getByRole('button', { name: '打开设置' }).click();
  await page.getByLabel('接口地址').fill(upstream.url);
  await page.getByLabel('API Key', { exact: true }).fill('parallel-test-secret');
  await page.getByLabel('模型 ID').fill('test-model');
  await page.getByLabel('模型名称').fill('并行测试模型');
  await page.getByRole('button', { name: '保存配置' }).click();
  upstream.enqueue({ chunks: ['甲的开头', '和甲的结尾'], pauseAfter: 0 });
  await page.getByRole('textbox', { name: '输入消息' }).fill('正在生成的甲会话');
  await page.getByRole('button', { name: '发送消息' }).click();
  await expect(page.getByTestId('assistant-message')).toHaveText('甲的开头');
  const firstId = new URL(page.url()).pathname.split('/').pop();
  await page.getByRole('button', { name: '新建会话', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '输入消息' })).toBeEnabled();
  upstream.enqueue({ chunks: ['乙的开头', '和乙的结尾'], pauseAfter: 0 });
  await page.getByRole('textbox', { name: '输入消息' }).fill('正在生成的乙会话');
  await page.getByRole('button', { name: '发送消息' }).click();
  await expect(page.getByTestId('assistant-message')).toHaveText('乙的开头');
  expect(upstream.requests).toHaveLength(2);
  await page.getByRole('button', { name: '正在生成的甲会话', exact: true }).click();
  await expect(page.getByTestId('assistant-message')).toHaveText('甲的开头');
  await expect(page.getByRole('button', { name: '发送消息' })).toBeDisabled();
  const duplicate = await page.request.post(`${workbench.url}/api/conversations/${firstId}/messages`, { data: { content: '不能重复发送' } });
  expect(duplicate.status()).toBe(409);
  await page.getByRole('button', { name: '正在生成的乙会话', exact: true }).click();
  upstream.release();
  await expect(page.getByTestId('assistant-message')).toHaveText('乙的开头和乙的结尾');
  await expect(page.getByRole('button', { name: '发送消息' })).toBeEnabled();
  await expect(page.getByTestId('user-message')).toHaveText('正在生成的乙会话');
  await page.getByRole('button', { name: '正在生成的甲会话', exact: true }).click();
  await expect(page.getByTestId('assistant-message')).toHaveText('甲的开头和甲的结尾');
  await expect(page.getByRole('button', { name: '发送消息' })).toBeEnabled();
  expect(upstream.requests).toHaveLength(2);
  expect(upstream.requests[1].messages.filter((message) => message.role === 'user')).toEqual([{ role: 'user', content: '正在生成的乙会话' }]);
});
