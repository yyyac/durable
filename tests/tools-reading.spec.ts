test('真实文件读取已打开后进程崩溃自动重放读取，完成调用在再次重启后不重跑', async ({ page, workbench, upstream }) => {
  test.setTimeout(45_000);
  test.skip(process.platform !== 'win32', '通过Windows文件共享模式确认真实读取句柄');
  await page.goto(workbench.url);
  await configureModel(page, upstream.url);
  const conversation = (await (await page.request.get(`${workbench.url}/api/conversations`)).json())[0];
  const path = join(conversation.defaultDirectory, 'recovery.txt');
  const large = await open(path, 'w');
  await large.truncate(1024 * 1024 * 1024);
  await large.write('\n崩溃前尚未返回的尾行', 1024 * 1024 * 1024);
  await large.close();
  const probe = await readHandleProbe(path);
  try {
    await page.request.post(`${workbench.url}/api/local-tools/enable`);
    await page.reload();
    upstream.enqueue({ chunks: [{ toolCall: { id: 'recovery-read', name: 'read', arguments: '{"path":"recovery.txt","offset":2,"limit":1}' } }] });
    upstream.enqueue({ chunks: ['恢复后读取完成'] });
    await page.getByRole('textbox', { name: '输入消息' }).fill('读取大文件的第二行');
    await page.getByRole('button', { name: '发送消息' }).click();
    await expect(page.getByRole('button', { name: /read recovery.txt 运行中/ })).toBeVisible();
    expect(await probe.check()).toBe(true);
    expect(upstream.requests).toHaveLength(1);
    await workbench.crash();
    await writeFile(path, '中断后文件已经更新\n自动恢复读到的新尾行');
    await workbench.start();
    await expect(page.getByTestId('assistant-message').last()).toHaveText('恢复后读取完成', { timeout: 12_000 });
    await page.getByRole('button', { name: /read recovery.txt 已完成/ }).click();
    await expect(page.getByTestId('tool-output')).toHaveText('自动恢复读到的新尾行');
    expect(JSON.stringify(upstream.requests[1].messages)).toContain('自动恢复读到的新尾行');
    expect(JSON.stringify(upstream.requests[1].messages)).not.toContain('崩溃前尚未返回的尾行');
    await workbench.crash();
    await workbench.start();
    await page.reload();
    await expect(page.getByRole('button', { name: /read recovery.txt 已完成/ })).toHaveCount(1);
    await expect(page.getByTestId('assistant-message').last()).toHaveText('恢复后读取完成');
    expect(upstream.requests).toHaveLength(2);
  } finally { probe.close(); }
});

test('运行中的真实读取可停止，卡片保留已停止状态并且不继续请求模型', async ({ page, workbench, upstream }) => {
  test.setTimeout(45_000);
  test.skip(process.platform !== 'win32', '通过Windows文件共享模式确认真实读取句柄');
  await page.goto(workbench.url);
  await configureModel(page, upstream.url);
  const conversation = (await (await page.request.get(`${workbench.url}/api/conversations`)).json())[0];
  const path = join(conversation.defaultDirectory, 'stop-read.txt');
  const large = await open(path, 'w');
  await large.truncate(1024 * 1024 * 1024);
  await large.write('\n停止后仍保留的文件内容', 1024 * 1024 * 1024);
  await large.close();
  const probe = await readHandleProbe(path);
  try {
    await page.request.post(`${workbench.url}/api/local-tools/enable`);
    await page.reload();
    upstream.enqueue({ chunks: [{ toolCall: { id: 'stopping-read', name: 'read', arguments: '{"path":"stop-read.txt","offset":2,"limit":1}' } }] });
    await page.getByRole('textbox', { name: '输入消息' }).fill('开始读取并停止');
    await page.getByRole('button', { name: '发送消息' }).click();
    await expect(page.getByRole('button', { name: /read stop-read.txt 运行中/ })).toBeVisible();
    expect(await probe.check()).toBe(true);
    expect(await page.getByRole('status', { name: '正在请求模型' }).count()).toBe(0);
    await page.getByRole('button', { name: '停止生成', exact: true }).click();
    await expect(page.getByRole('button', { name: /read stop-read.txt 已停止/ })).toHaveCount(1);
    await expect(page.getByRole('button', { name: '发送消息', exact: true })).toBeEnabled();
    expect((await stat(path)).size).toBeGreaterThan(1024 * 1024 * 1024);
    expect(upstream.requests).toHaveLength(1);
    await page.reload();
    await expect(page.getByRole('button', { name: /read stop-read.txt 已停止/ })).toHaveCount(1);
    upstream.enqueue({ chunks: ['停止后可以继续聊天'] });
    await page.getByRole('textbox', { name: '输入消息' }).fill('继续聊天');
    await page.getByRole('button', { name: '发送消息' }).click();
    await expect(page.getByTestId('assistant-message').last()).toHaveText('停止后可以继续聊天');
  } finally { probe.close(); }
});

test('思考正文和工具按执行顺序显示，切换刷新接续后保留唯一完整输出与折叠状态', async ({ page, workbench, upstream }) => {
  await page.goto(workbench.url);
  await configureModel(page, upstream.url, { supportsThinking: true });
  const conversation = (await (await page.request.get(`${workbench.url}/api/conversations`)).json())[0];
  await writeFile(join(conversation.defaultDirectory, 'ordered.txt'), '真实输出头\n真实输出尾');
  await page.request.post(`${workbench.url}/api/local-tools/enable`);
  await page.reload();
  upstream.enqueue({ chunks: [{ thinking: '先确认需要读取文件' }, '读取前正文', { toolCall: { id: 'ordered-read', name: 'read', arguments: '{"path":"ordered.txt"}' } }] });
  upstream.enqueue({ chunks: ['读取后首段', '与最终尾段'], pauseAfter: 0 });
  await page.getByRole('textbox', { name: '输入消息' }).fill('验证工具顺序');
  await page.getByRole('button', { name: '发送消息' }).click();
  await expect(page.getByTestId('assistant-message').last()).toHaveText('读取后首段');
  const beforeSwitch = (await page.getByTestId('assistant-message').allTextContents()).join('\n');
  expect(beforeSwitch.indexOf('思考过程')).toBeLessThan(beforeSwitch.indexOf('读取前正文'));
  expect(beforeSwitch.indexOf('读取前正文')).toBeLessThan(beforeSwitch.indexOf('read'));
  expect(beforeSwitch.indexOf('read')).toBeLessThan(beforeSwitch.indexOf('读取后首段'));
  await expect(page.getByRole('button', { name: /read ordered.txt 已完成/ })).toHaveAttribute('aria-expanded', 'false');
  await page.getByRole('button', { name: '新建会话', exact: true }).click();
  upstream.enqueue({ chunks: ['另一个会话继续可用'] });
  await page.getByRole('textbox', { name: '输入消息' }).fill('另一段独立对话');
  await page.getByRole('button', { name: '发送消息' }).click();
  await expect(page.getByTestId('assistant-message')).toHaveText('另一个会话继续可用');
  await page.getByRole('button', { name: '验证工具顺序', exact: true }).click();
  await expect(page.getByTestId('assistant-message').last()).toHaveText('读取后首段');
  await page.reload();
  const tool = page.getByRole('button', { name: /read ordered.txt 已完成/ });
  await tool.click();
  await expect(page.getByTestId('tool-output')).toHaveText('真实输出头\n真实输出尾');
  upstream.release();
  await expect(page.getByTestId('assistant-message').last()).toHaveText('读取后首段与最终尾段');
  await expect(tool).toHaveAttribute('aria-expanded', 'true');
  await expect(tool).toHaveCount(1);
  await expect(page.getByTestId('tool-output')).toHaveText('真实输出头\n真实输出尾');
  expect(upstream.requests).toHaveLength(3);
});

