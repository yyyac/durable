test('首次启用前纯聊天，确认后从独立目录读取真实文件并将结果交回模型，信任跨重启保留', async ({ page, workbench, upstream }) => {
  await page.goto(workbench.url);
  await configureModel(page, upstream.url);
  const conversation = (await (await page.request.get(`${workbench.url}/api/conversations`)).json())[0];
  await writeFile(join(conversation.defaultDirectory, 'note.txt'), '真实文件内容：春江潮水');
  upstream.enqueue({ chunks: ['未启用时可以聊天'] });
  await page.getByRole('textbox', { name: '输入消息' }).fill('先聊一句');
  await page.getByRole('button', { name: '发送消息' }).click();
  await expect(page.getByTestId('assistant-message')).toHaveText('未启用时可以聊天');
  expect(upstream.requests[0].tools ?? []).toHaveLength(0);
  await page.getByRole('button', { name: '启用本机工具', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '启用本机工具' });
  await expect(dialog).toContainText(conversation.defaultDirectory);
  await expect(dialog).toContainText('并非目录沙箱');
  await expect(dialog).toContainText('后端进程');
  await dialog.getByRole('button', { name: '确认启用', exact: true }).click();
  upstream.enqueue({ chunks: ['先读取文件。', { toolCall: { id: 'read-note', name: 'read', arguments: '{"path":' } }, { toolCall: { arguments: '"note.txt"}' } }] });
  upstream.enqueue({ chunks: ['已读到真实文件'] });
  await page.getByRole('textbox', { name: '输入消息' }).fill('读取 note.txt');
  await page.getByRole('button', { name: '发送消息' }).click();
  await expect(page.getByTestId('assistant-message').last()).toHaveText('已读到真实文件');
  const tool = page.getByRole('button', { name: /read note.txt 已完成/ });
  await expect(tool).toHaveCount(1);
  await tool.click();
  await expect(page.getByTestId('tool-output')).toContainText('真实文件内容：春江潮水');
  expect(upstream.requests[1].tools).toHaveLength(3);
  expect(upstream.requests[2].messages.find((message) => message.role === 'tool')?.content).toContain('真实文件内容：春江潮水');
  await workbench.stop();
  await workbench.start();
  await page.reload();
  await expect(page.getByRole('button', { name: '启用本机工具', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: /read note.txt 已完成/ })).toHaveCount(1);
  await page.getByRole('button', { name: '新建会话', exact: true }).click();
  await expect(page.getByRole('button', { name: '启用本机工具', exact: true })).toHaveCount(0);
  expect(upstream.requests).toHaveLength(3);
});

