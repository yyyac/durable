test('工作区命令确认重试受十个名额与原会话互斥约束，重复确认只追加一次真实效果', async ({ page, workbench, upstream }) => {
  test.setTimeout(90_000);
  await page.goto(workbench.url);
  await configureModel(page, upstream.url);
  const directory = join(workbench.dataDir, 'command-retry');
  await mkdir(directory);
  const session = (await (await page.request.post(`${workbench.url}/api/workspaces`, { data: { path: directory, trusted: true } })).json()).conversation;
  await page.goto(`${workbench.url}/conversations/${session.id}`);
  const command = await commandTree(directory);
  const effect = crashAfterFileEffect(workbench, directory, 'tree-ready.txt');
  try {
    upstream.enqueue({ chunks: [{ toolCall: { id: 'retry-command', name: 'powershell', arguments: JSON.stringify({ command }) } }] });
    await page.getByRole('textbox', { name: '输入消息' }).fill('工作区中断命令待确认');
    await page.getByRole('button', { name: '发送消息' }).click();
    await effect.crashed;
    await workbench.start();
    await page.reload();
    await expect(page.getByRole('button', { name: '确认重试', exact: true })).toBeVisible({ timeout: 12_000 });
    const other = await (await page.request.post(`${workbench.url}/api/conversations`)).json();
    upstream.enqueue({ chunks: ['其他会话可以完成'] });
    expect((await page.request.post(`${workbench.url}/api/conversations/${other.id}/messages`, { data: { content: '其他会话不能放行旧命令' } })).status()).toBe(202);
    await expect.poll(() => upstream.finishedResponses).toBe(2);
    expect(upstream.requests).toHaveLength(2);
    expect(await readFile(join(directory, 'attempts.txt'), 'utf8')).toBe('执行一次\n');
    const active = await Promise.all(Array.from({ length: 10 }, async () => (await (await page.request.post(`${workbench.url}/api/conversations`)).json())));
    for (let index = 0; index < 10; index++) upstream.enqueue({ chunks: [`占用命令重试名额${index}`, '完成'], pauseAfter: 0 });
    const starts = await Promise.all(active.map((item) => page.request.post(`${workbench.url}/api/conversations/${item.id}/messages`, { data: { content: '占用全局名额' } })));
    expect(starts.map((response) => response.status())).toEqual(Array(10).fill(202));
    await expect.poll(() => upstream.requests.length).toBe(12);
    const posted = page.waitForRequest((request) => request.url().endsWith('/retry') && request.method() === 'POST');
    await page.getByRole('button', { name: '确认重试', exact: true }).click();
    const retry = await posted;
    await expect(page.getByRole('alert')).toContainText('最多同时运行 10 个会话');
    expect(await readFile(join(directory, 'attempts.txt'), 'utf8')).toBe('执行一次\n');
    expect((await page.request.post(`${workbench.url}/api/conversations/${session.id}/messages`, { data: { content: '等待期间不能发送' } })).status()).toBe(409);
    expect((await page.request.post(`${workbench.url}/api/conversations/${active[0].id}/stop`)).status()).toBe(200);
    upstream.enqueue({ chunks: ['原命令确认重试完成'] });
    const confirmations = await Promise.all([0, 1].map(() => page.request.post(retry.url(), { data: retry.postDataJSON() })));
    expect(confirmations.map((response) => response.status())).toEqual([202, 202]);
    await expect(page.getByTestId('assistant-message').last()).toHaveText('原命令确认重试完成', { timeout: 15_000 });
    expect(await readFile(join(directory, 'attempts.txt'), 'utf8')).toBe('执行一次\n执行一次\n');
    expect(upstream.requests).toHaveLength(13);
    expect(JSON.stringify(upstream.requests[12].messages)).toContain('原命令已完成');
    expect(JSON.stringify(upstream.requests[12].messages)).toContain('退出码：0');
    expect(JSON.stringify(upstream.requests[12].messages)).not.toContain('was interrupted');
    expect((await page.request.post(retry.url(), { data: retry.postDataJSON() })).status()).toBe(202);
    await workbench.crash();
    await workbench.start();
    await page.reload();
    await expect(page.getByRole('button', { name: /powershell .*已完成/ })).toHaveCount(1);
    expect(await readFile(join(directory, 'attempts.txt'), 'utf8')).toBe('执行一次\n执行一次\n');
    await expect(access(join(directory, 'late-effect.txt'))).rejects.toThrow();
  } finally { effect.close(); upstream.release(); }
});

