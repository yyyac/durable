test('长命令输出保留尾部，超时失败仍保留完整输出日志供查看', async ({ page, workbench, upstream }) => {
  test.setTimeout(60_000);
  await page.goto(workbench.url);
  await configureModel(page, upstream.url);
  await page.request.post(`${workbench.url}/api/local-tools/enable`);
  await page.reload();
  upstream.enqueue({ chunks: [{ toolCall: { id: 'long-output-timeout', name: 'powershell', arguments: JSON.stringify({ command: '1..2500 | ForEach-Object { [Console]::WriteLine(("{0:D4}:" -f $_) + ("文" * 30)) }; [Console]::WriteLine("末尾中文🙂"); Start-Sleep -Seconds 30', timeout: 2.5 }) } }] });
  upstream.enqueue({ chunks: ['已收到长输出和超时诊断'] });
  await page.getByRole('textbox', { name: '输入消息' }).fill('运行长输出命令并超时');
  await page.getByRole('button', { name: '发送消息' }).click();
  await expect(page.getByTestId('assistant-message').last()).toHaveText('已收到长输出和超时诊断', { timeout: 30_000 });
  await page.getByRole('button', { name: /powershell .*失败/ }).click();
  await expect(page.getByTestId('tool-output')).toContainText('末尾中文🙂');
  await expect(page.getByTestId('tool-output')).toContainText('Full output:');
  const output = await page.getByTestId('tool-output').innerText();
  expect(output).not.toContain('0001:');
  const fullPath = /Full output: ([^\r\n]+)/.exec(output)?.[1];
  expect(fullPath).toBeTruthy();
  const full = await readFile(fullPath!, 'utf8');
  expect(full).toContain('0001:');
  expect(full).toContain('末尾中文🙂');
  expect(JSON.stringify(upstream.requests[1].messages)).toContain('Full output:');
  await page.reload();
  await page.getByRole('button', { name: /powershell .*失败/ }).click();
  await expect(page.getByTestId('tool-output')).toContainText(fullPath!);
});
