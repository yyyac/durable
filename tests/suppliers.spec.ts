import { test, expect } from './fixtures';
import { addModelService, configureModel, openModelSettings } from './configure-model';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

test('供应商列表只展示已保存记录，新增和编辑取消时丢弃草稿', async ({ page, workbench, upstream }) => {
  await page.goto(workbench.url);
  await page.getByRole('button', { name: '打开设置' }).click();
  const providers = page.getByRole('region', { name: '自定义供应商', exact: true });
  await expect(providers.getByRole('button')).toHaveCount(0);
  await expect(page.getByLabel('服务名称')).toHaveCount(0);
  await page.getByRole('button', { name: '添加供应商', exact: true }).click();
  await page.getByLabel('服务名称').fill('不会保存的供应商');
  await page.getByRole('button', { name: '返回供应商列表' }).click();
  await expect(providers.getByRole('button')).toHaveCount(0);
  expect(await (await page.request.get(`${workbench.url}/api/settings`)).json()).toBeNull();
  await addModelService(page);
  await page.getByLabel('服务名称').fill('自定义服务');
  await page.getByLabel('接口地址').fill(upstream.url);
  await page.getByLabel('API Key', { exact: true }).fill('supplier-secret');
  await page.getByLabel('模型 ID', { exact: true }).fill('custom-model');
  await page.getByLabel('模型名称', { exact: true }).fill('自定义模型');
  await page.getByRole('button', { name: '保存配置' }).click();
  await expect(providers.getByRole('button', { name: '自定义服务', exact: true })).toContainText('1 个模型');
  await expect(page.getByRole('dialog', { name: '模型设置' })).toBeVisible();
  await openModelSettings(page, '自定义服务');
  await expect(page.getByLabel('API Key', { exact: true })).toHaveAttribute('placeholder', '••••••••••••••••');
  await page.getByLabel('服务名称').fill('放弃的名称');
  await page.getByLabel('上下文', { exact: true }).fill('1000000');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await expect(providers.getByRole('button', { name: '自定义服务', exact: true })).toBeVisible();
  await openModelSettings(page, '自定义服务');
  await expect(page.getByLabel('服务名称')).toHaveValue('自定义服务');
  await expect(page.getByLabel('上下文', { exact: true })).toHaveValue('131072');
  await page.getByLabel('服务名称').fill('保存后的服务');
  await page.getByLabel('最大输出', { exact: true }).fill('8192');
  await page.getByRole('button', { name: '保存配置' }).click();
  await expect(providers.getByRole('button')).toHaveCount(1);
  await expect(providers.getByRole('button', { name: '保存后的服务', exact: true })).toBeVisible();
  await workbench.stop(); await workbench.start(); await page.reload();
  await openModelSettings(page, '保存后的服务');
  await expect(page.getByLabel('最大输出', { exact: true })).toHaveValue('8192');
});

test('单独保存供应商保留其它密钥，删除失败可重试并正确更新所选模型', async ({ page, workbench, upstream }) => {
  await page.goto(workbench.url);
  await configureModel(page, upstream.url, { apiKey: 'first-supplier-key' });
  await addModelService(page);
  await page.getByLabel('服务名称').fill('第二供应商');
  await page.getByLabel('接口地址').fill(upstream.url);
  await page.getByLabel('API Key', { exact: true }).fill('second-supplier-key');
  await page.getByLabel('模型 ID', { exact: true }).fill('second-model');
  await page.getByLabel('模型名称', { exact: true }).fill('第二模型');
  await page.getByRole('button', { name: '保存配置' }).click();
  await openModelSettings(page, '模型服务');
  await page.getByLabel('服务名称').fill('第一供应商');
  await page.getByRole('button', { name: '保存配置' }).click();
  const stored = JSON.parse(await readFile(join(workbench.dataDir, 'models.json'), 'utf8'));
  expect(stored.services.map((service: { apiKey: string }) => service.apiKey)).toEqual(['first-supplier-key', 'second-supplier-key']);
  await openModelSettings(page, '第一供应商');
  await page.route('**/api/settings', (route) => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: '暂时无法删除' }) }), { times: 1 });
  await page.getByRole('button', { name: '移除模型服务' }).click();
  await expect(page.getByRole('alert')).toHaveText('暂时无法删除');
  await expect(page.getByLabel('服务名称')).toHaveValue('第一供应商');
  await page.getByRole('button', { name: '移除模型服务' }).click();
  const providers = page.getByRole('region', { name: '自定义供应商', exact: true });
  await expect(providers.getByRole('button')).toHaveCount(1);
  await expect(providers.getByRole('button', { name: '第二供应商', exact: true })).toBeVisible();
  const remaining = await (await page.request.get(`${workbench.url}/api/settings`)).json();
  expect(remaining.selectedModel.serviceId).toBe(remaining.services[0].id);
  expect(remaining.services[0].name).toBe('第二供应商');
  await openModelSettings(page, '第二供应商');
  await page.getByRole('button', { name: '移除模型服务' }).click();
  await expect(providers.getByRole('button')).toHaveCount(0);
  expect((await (await page.request.get(`${workbench.url}/api/settings`)).json()).selectedModel).toBeNull();
  await page.getByRole('button', { name: '关闭设置' }).click();
  await expect(page.getByText('尚未配置模型', { exact: true })).toBeVisible();
});
